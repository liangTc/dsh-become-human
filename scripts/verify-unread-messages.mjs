import assert from 'node:assert/strict';
import {UnreadMessages} from '../plugins/become-human-web/unread-messages.mjs';
const values=new Map(),storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
const state={sessionId:'test-only',messages:[{seq:1,kind:'assistant',text:'old'}]};
const cursor=new UnreadMessages(storage);
assert.equal(cursor.update(state),false,'Initial history must not appear as new messages');
state.messages.push({seq:2,kind:'user',text:'input'},{seq:3,kind:'dispatch',text:'status'});
assert.equal(cursor.update(state),false,'Input and status must not notify');
state.messages.push({seq:4,kind:'assistant',text:'reply',bubbleParts:['one','two']});
assert.equal(cursor.update(state),true);
assert.equal(cursor.update(state),true,'Repeated polling must retain pending unread state');
const reloaded=new UnreadMessages(storage);
assert.equal(reloaded.update(state),true,'Unread survives reload');
assert.equal(reloaded.read('wrong-session',4),true);
assert.equal(reloaded.read(state.sessionId,1),true);
assert.equal(reloaded.read(state.sessionId,4),false);
assert.equal(new UnreadMessages(storage).update(state),false,'Acknowledgement survives reload');
state.messages.push({seq:5,kind:'budget-request',text:'approval needed'});
assert.equal(reloaded.update(state),true);
assert.equal(reloaded.read(state.sessionId,4),true,'Acknowledging older content cannot clear a new message');
assert.equal(reloaded.update({...state,sessionId:'other-session'}),false);
assert.equal(reloaded.update(state),true,'Session cursors remain separate');
const denied=new UnreadMessages({getItem(){throw Error('denied');},setItem(){throw Error('denied');}});
assert.equal(denied.update(state),false);
assert.equal(denied.update({...state,messages:[...state.messages,{seq:6,kind:'assistant',text:'new'}]}),true);
const alertCursor=new UnreadMessages(storage);alertCursor.update(state);alertCursor.read(state.sessionId,5);
assert.equal(alertCursor.update({...state,messages:[...state.messages,{seq:6,kind:'model-error',text:'模型调用异常'}]}),true);
console.log(JSON.stringify({passed:16,scope:'isolated unread state; no production messages'}));
